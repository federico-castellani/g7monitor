/** What the configurable number of an alarm means. */
enum class ValueKind { Glucose, Rate, Minutes }

/** Sounds shipped with the app (res/raw, generated by tools/gen_alarm_sounds.py). */
enum class BuiltInSound(@param:StringRes private val labelRes: Int, val res: Int) {
    UrgentLow(R.string.sound_urgent_low, R.raw.alarm_urgent_low),
    Low(R.string.sound_low, R.raw.alarm_low),
    UrgentHigh(R.string.sound_urgent_high, R.raw.alarm_urgent_high),
    High(R.string.sound_high, R.raw.alarm_high),
    Falling(R.string.sound_falling, R.raw.alarm_falling),
    Rising(R.string.sound_rising, R.raw.alarm_rising),
    Signal(R.string.sound_signal, R.raw.alarm_signal);

    val label: String get() = str(labelRes)
}

/**
 * @param priority lower rings first when several alarms are true at once.
 * @param value default threshold: mg/dL, mg/dL/min ×10, or minutes.
 */
enum class AlarmType(
    @param:StringRes private val titleRes: Int,
    @param:StringRes private val descriptionRes: Int,
    val priority: Int,
    val kind: ValueKind,
    val value: Int,
    val range: IntRange,
    val step: Int,
    val enabled: Boolean,
    val snoozeMin: Int,
    val sound: BuiltInSound,
    val urgent: Boolean,
) {
    UrgentLow(R.string.alarm_urgent_low, R.string.alarm_urgent_low_text, 0,
        ValueKind.Glucose, 55, 40..70, 1, true, 15, BuiltInSound.UrgentLow, true),
    Low(R.string.alarm_low, R.string.alarm_low_text, 2,
        ValueKind.Glucose, 70, 55..100, 1, true, 30, BuiltInSound.Low, false),
    UrgentHigh(R.string.alarm_urgent_high, R.string.alarm_urgent_high_text, 3,
        ValueKind.Glucose, 250, 180..400, 5, true, 30, BuiltInSound.UrgentHigh, true),
    High(R.string.alarm_high, R.string.alarm_high_text, 5,
        ValueKind.Glucose, 180, 120..300, 5, true, 60, BuiltInSound.High, false),
    FallingFast(R.string.alarm_falling, R.string.alarm_falling_text, 4,
        ValueKind.Rate, 20, 10..50, 5, true, 30, BuiltInSound.Falling, false),
    RisingFast(R.string.alarm_rising, R.string.alarm_rising_text, 6,
        ValueKind.Rate, 20, 10..50, 5, false, 30, BuiltInSound.Rising, false),
    SignalLoss(R.string.alarm_signal, R.string.alarm_signal_text, 1,
        ValueKind.Minutes, 20, 10..120, 5, true, 30, BuiltInSound.Signal, false);

    val title: String get() = str(titleRes)
    val description: String get() = str(descriptionRes)
}

enum class AlarmOutput(@param:StringRes private val labelRes: Int) {
    SoundAndVibration(R.string.output_both),
    VibrationOnly(R.string.output_vibration),
    SoundOnly(R.string.output_sound);

    val label: String get() = str(labelRes)
}

/**
 * User settings of one alarm.
 * @param sound a [BuiltInSound] name, or a content URI chosen with the system sound picker.
 * @param volume 0–100, relative to the phone's alarm volume.
 */
data class AlarmConfig(
    val type: AlarmType,
    val enabled: Boolean = type.enabled,
    val value: Int = type.value,
    val snoozeMin: Int = type.snoozeMin,
    val output: AlarmOutput = AlarmOutput.SoundAndVibration,
    val sound: String = type.sound.name,
    val volume: Int = 100,
) {
    val builtInSound: BuiltInSound? get() = BuiltInSound.entries.firstOrNull { it.name == sound }

    fun toJson(): String = JSONObject()
        .put("enabled", enabled).put("value", value).put("snooze", snoozeMin)
        .put("output", output.name).put("sound", sound).put("volume", volume)
        .toString()

    companion object {
        /** Unknown or out-of-range values fall back to the defaults, so an old or broken entry can't disable safety. */
        fun fromJson(type: AlarmType, json: String?): AlarmConfig {
            val d = AlarmConfig(type)
            val o = json?.let { runCatching { JSONObject(it) }.getOrNull() } ?: return d
            return AlarmConfig(
                type = type,
                enabled = o.optBoolean("enabled", d.enabled),
                value = o.optInt("value", d.value).takeIf { it in type.range } ?: d.value,
                snoozeMin = o.optInt("snooze", d.snoozeMin).takeIf { it in 5..120 } ?: d.snoozeMin,
                output = AlarmOutput.entries.firstOrNull { it.name == o.optString("output") } ?: d.output,
                sound = o.optString("sound").ifBlank { d.sound },
                volume = o.optInt("volume", d.volume).coerceIn(10, 100),
            )
        }
    }
}

private val Context.alarmStore by preferencesDataStore("alarms")

class AlarmRepository(private val context: Context) {
    private fun key(t: AlarmType) = stringPreferencesKey("alarm_${t.name}")

    val configs: Flow<Map<AlarmType, AlarmConfig>> = context.alarmStore.data.map { prefs ->
        AlarmType.entries.associateWith { AlarmConfig.fromJson(it, prefs[key(it)]) }
    }

    suspend fun current(): Map<AlarmType, AlarmConfig> = configs.first()

    suspend fun save(config: AlarmConfig) {
        context.alarmStore.edit { it[key(config.type)] = config.toJson() }
    }

    private val pausedKey = longPreferencesKey("alarms_paused_until")

    /**
     * All alarms silenced until this time ([PAUSED_UNTIL_RESUMED]: until turned back on), null when
     * active. Each alarm keeps its own switch, so resuming brings back exactly the ones that were on.
     * An expired time is removed by [AlarmEngine.evaluate].
     */
    val pausedUntil: Flow<Long?> = context.alarmStore.data.map { it[pausedKey] }

    suspend fun pausedUntil(): Long? = pausedUntil.first()

    suspend fun setPausedUntil(until: Long?) {
        context.alarmStore.edit { if (until == null) it.remove(pausedKey) else it[pausedKey] = until }
    }

    companion object {
        const val PAUSED_UNTIL_RESUMED = Long.MAX_VALUE
    }
}
